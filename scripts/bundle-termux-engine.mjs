/**
 * Bundles the deterministic Planner engine (Termux entry) into a single
 * self-contained ESM file at termux/planner-engine.mjs using Node built-ins
 * only — so the phone never needs npm install.
 *
 * Run: node scripts/bundle-termux-engine.mjs
 */
import { rolldown } from "rolldown";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "termux");
const outFile = resolve(outDir, "planner-engine.mjs");

mkdirSync(outDir, { recursive: true });

const bundle = await rolldown({
  input: resolve(root, "src/lib/planner/termux-entry.ts"),
  platform: "node",
  target: "node22",
  format: "esm",
  bundle: true,
  external: ["node:http", "node:fs", "node:path"],
  minify: false,
});

const result = await bundle.generate();
const code = result.output
  .map((o) => ("code" in o ? o.code : ""))
  .join("\n");

const header = `#!/usr/bin/env node
// Generated by scripts/bundle-termux-engine.mjs — do not edit by hand.
// Source: src/lib/planner/termux-entry.ts (+ engine/goals/behavior/contract/tools/types).
// Runs the deterministic Stone* Planner engine as a standalone REST service.
`;
writeFileSync(outFile, header + "\n" + code, "utf8");
writeFileSync(resolve(outDir, ".gitignore"), "*\n!planner-engine.mjs\n!planner.env.example\n!llama-setup.sh\n!HANDOFF.md\n", "utf8");
console.log(`wrote ${outFile} (${code.length} chars)`);